/**
 * Synchronize static DOM elements in English
 */
export function updateStaticDOMElements() {
  // 1. Desktop Navigation
  const navDesktop = document.querySelector('.nav-desktop');
  if (navDesktop) {
    const links = navDesktop.querySelectorAll('.nav-link');
    links.forEach((link, idx) => {
      const href = link.getAttribute('href');
      const dataNav = link.getAttribute('data-nav');
      const text = (link.textContent || '').trim().toLowerCase();
      if (dataNav === 'home' || (idx === 0 && (href === '#forms' || href === '#home')) || text === 'home') {
        link.textContent = t('nav_home') || 'Home';
      } else if (dataNav === 'forms' || href === '#forms' || href === '#forum') {
        link.innerHTML = `Forms <span class="nav-link-badge">New</span>`;
      }
      else if (href === '#novels?category=Ongoing') link.innerText = t('nav_whats_new');
      else if (href === '#members') link.innerText = t('nav_members');
      else if (href.includes('pratilipi.com')) link.innerText = t('nav_pratilipi');
      else if (href === '#contact') link.innerText = t('nav_contact');
      else if (href.includes('youtube.com')) link.innerText = t('nav_youtube');
    });
  }

  // 2. Mobile Drawer Navigation
  const drawerNav = document.querySelector('.drawer-nav');
  if (drawerNav) {
    const links = drawerNav.querySelectorAll('.drawer-nav-item');
    links.forEach((link, idx) => {
      const href = link.getAttribute('href');
      const dataNav = link.getAttribute('data-nav');
      const text = (link.textContent || '').trim().toLowerCase();
      if (dataNav === 'home' || (idx === 0 && (href === '#forms' || href === '#home')) || text === 'home') {
        link.textContent = t('nav_home') || 'Home';
      } else if (dataNav === 'forms' || href === '#forms' || href === '#forum') {
        link.innerText = 'Forms';
      }
      else if (href === '#novels?category=Ongoing') link.innerText = t('nav_whats_new');
      else if (href === '#members') link.innerText = t('nav_members');
      else if (href.includes('pratilipi.com')) link.innerText = t('nav_pratilipi');
      else if (href === '#contact') link.innerText = t('nav_contact');
      else if (href.includes('youtube.com')) link.innerText = `▶ ${t('nav_youtube_channel')}`;
    });
  }

  // 3. Search Modal Placeholders & Filter Pills
  const searchInput = document.getElementById('search-input');
  if (searchInput) searchInput.placeholder = t('search_placeholder');

  const searchPills = document.querySelectorAll('.search-pill');
  searchPills.forEach(pill => {
    const filter = pill.dataset.filter;
    if (filter === 'all') pill.innerText = t('search_all');
    else if (filter === 'novels') pill.innerText = t('search_novels');
    else if (filter === 'topics') pill.innerText = t('search_topics');
    else if (filter === 'members') pill.innerText = t('search_members');
  });

  // 4. Auth Modal Title & Labels
  const authTitle = document.getElementById('auth-modal-title');
  if (authTitle) {
    authTitle.innerText = t('auth_login_title');
  }

  // 5. Notifications Header
  const notifHeaderSpan = document.querySelector('.notif-header > span');
  if (notifHeaderSpan) notifHeaderSpan.innerText = t('notif_title');
  const markReadBtn = document.getElementById('mark-all-read-btn');
  if (markReadBtn) markReadBtn.innerText = t('notif_mark_all_read');

  // 6. Footer Static Text
  const footerDesc = document.querySelector('.footer-desc');
  if (footerDesc) footerDesc.innerText = t('footer_desc');

  const footerTitles = document.querySelectorAll('.footer-title');
  if (footerTitles[0]) footerTitles[0].innerText = t('footer_quick_links');
  if (footerTitles[1]) footerTitles[1].innerText = t('footer_legal');
  if (footerTitles[2]) footerTitles[2].innerText = t('community_subtitle');

  const footerLinks = document.querySelectorAll('.footer-links');
  if (footerLinks[0]) {
    const qLinks = footerLinks[0].querySelectorAll('.footer-link');
    if (qLinks[0]) qLinks[0].innerText = t('nav_home');
    if (qLinks[1]) qLinks[1].innerText = t('nav_novels');
    if (qLinks[2]) qLinks[2].innerText = t('nav_forum');
    if (qLinks[3]) qLinks[3].innerText = t('nav_members');
    if (qLinks[4]) qLinks[4].innerText = t('nav_pratilipi');
    if (qLinks[5]) qLinks[5].innerText = t('nav_contact');
    if (qLinks[6]) qLinks[6].innerText = t('nav_youtube_channel');
  }

  if (footerLinks[1]) {
    const lLinks = footerLinks[1].querySelectorAll('.footer-link');
    if (lLinks[0]) lLinks[0].innerText = t('footer_privacy');
    if (lLinks[1]) lLinks[1].innerText = t('footer_terms');
    if (lLinks[2]) lLinks[2].innerText = t('footer_copyright');
    if (lLinks[3]) lLinks[3].innerText = t('footer_disclaimer');
  }

  const footerBottom = document.querySelector('.footer-bottom');
  if (footerBottom) {
    const divs = footerBottom.querySelectorAll('div');
    if (divs[0]) divs[0].innerText = t('footer_rights');
    if (divs[1]) divs[1].innerText = t('footer_tagline');
  }

  const footerCommDesc = document.querySelector('.footer-community-desc');
  if (footerCommDesc) footerCommDesc.innerText = t('community_desc');

  const footerJoinBtn = document.querySelector('.footer-join-btn');
  if (footerJoinBtn) footerJoinBtn.innerText = t('community_btn');

  const messagesTitle = document.querySelector('.messages-header h3');
  if (messagesTitle) messagesTitle.innerText = 'Messages';
}

